"""Generate validation metadata from the exact accepted OAS, never a second schema.
Usage: python3 tools/sourcefacts/generate.py /path/to/mvp-openapi.json
"""
import hashlib,json,pathlib,subprocess,sys
raw=pathlib.Path(sys.argv[1]).read_bytes()
assert hashlib.sha256(raw).hexdigest()=='a0c65940c8175de884bd404bc1187ace3be3c009737cc40b047e550e3f2c2b9e', 'wrong OAS bytes'
s=json.loads(raw)['components']['schemas']['SourceFacts']
assert s['type']=='object' and s['additionalProperties'] is False
assert set(s['required'])==set(s['properties'])
lines=['// Code generated by tools/sourcefacts/generate.py; DO NOT EDIT.', '// Source: hitpipe/project-os@fedbe40bb597e25f66aeb1172af3ff7459c81b40', '// contracts/hitpipe/mvp-2026-10-31/formal/mvp-openapi.json#/components/schemas/SourceFacts', 'package sourcefacts', '', 'var wireFields = map[string]fieldRule{']
for name,shape in sorted(s['properties'].items()):
 nullable='anyOf' in shape
 if nullable:
  assert len(shape['anyOf'])==2 and shape['anyOf'][1]=={'type':'null'}
  shape=shape['anyOf'][0]
 assert set(shape)<=set(['type','minimum','maximum','enum','format','pattern','minLength','maxLength'])
 assert shape['type'] in ['string','boolean','integer']
 fields=['kind: '+json.dumps(shape['type']),'nullable: '+str(nullable).lower()]
 for k,g in [('format','format'),('pattern','pattern'),('minLength','minLength'),('maxLength','maxLength'),('minimum','minimum'),('maximum','maximum')]:
  if k in shape: fields.append(g+': '+json.dumps(shape[k]))
 if 'enum' in shape:fields.append('choices: []string{'+','.join(json.dumps(x) for x in shape['enum'])+'}')
 lines.append(json.dumps(name)+': {'+', '.join(fields)+'},')
lines.append('}')
out=pathlib.Path(__file__).resolve().parents[2]/'internal/adapters/intake/sourcefacts/schema_generated.go'
out.write_text('\n'.join(lines)+'\n');subprocess.run(['gofmt','-w',str(out)],check=True)
